///////////////////////////////*INITIAL USFULL REGISTERS IN PIC12F1822*///////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
void PIC12F1822_INITIAL(void)
{
	INTCON=0b00000000;         //Disabled all interupts
	OSCCON=0b00111010;         //Use internal oscillator block,oscillator:500KHZ,4xPLL is disable
	APFCON=0b00000000;         //PORTA as I/O only
	ANSELA=0b00000000;         //PORTA as digital only
	TRISA =0b00001000;         //RA(0-2)+RA(4-5) as outputs,RA3 as input    
	PORTA =0b00000000;         //Reset the data on pins of PORTA
}
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////*WRITE UNSIGNED LONG INTEGER TO EEPROM IN PIC12F1822*//////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
void PIC12F1822_WRITE_UNSLON_EEPROM_PIC12F1822(unsigned char address,unsigned long data)
{
	unsigned char index; 
	unsigned long data_write;             

	for(index=0;index<4;index++)
	{
		data_write=(unsigned char)(data & 0x000000ff);	//Delete all except low byte
		eeprom_write(address,data_write);				//Write command to pic!
		address++;                     					//The next adress to keep the next byte
		data=data>>8;   							    //Rotate left 8 bits 
	}
	
	OUTPUT0 = 1;
}
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
///////////////////////////////*READ UNSIGNED LONG INTEGER FROM EEPROM IN PIC12F1822*/////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
unsigned long PIC12F1822_READ_UNSLON_EEPROM_PIC12F1822(unsigned char address)
{
	unsigned char data;
	unsigned int index;                     
	unsigned long data_read=0;               			//The number to find

	address+=3;											//Start from the high byte
	for(index=0;index<4;index++)
	{
		data=eeprom_read(address);						//Read command from pic!
		address--;                    					
		data_read=(data_read<<8) | data;               		
	}

	return data_read;
}
